import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { execFileSync, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const [prefix, variant, projectDirectory] = process.argv.slice(2);
assert(prefix && projectDirectory && ['ps', 'lean'].includes(variant));
const modules = path.join(prefix, ...(process.platform === 'win32' ? ['node_modules'] : ['lib', 'node_modules']));
const packageRoot = path.join(modules, 'proofscript');
const cli = path.join(packageRoot, 'bin/psc.js');
assert(existsSync(cli), 'installed CLI missing');
const meta = JSON.parse(await readFile(path.join(packageRoot, 'package.json'), 'utf8'));
assert.equal(meta.proofscript.architectureHost, 'checked-host/1');
for (const optional of meta.proofscript.optionalPackages) assert(!existsSync(path.join(packageRoot, 'node_modules', optional)), 'optional package was bundled: ' + optional);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const reportDir = path.join(root, 'dist/architecture-evidence');
await mkdir(reportDir, { recursive: true });
// Read/parse the whole installed compiler closure, without elaborating or
// regenerating C1/C2/C3. The byte-identity guard carries the qualified semantics.
const runtime = await import(pathToFileURL(path.join(packageRoot, 'node_modules/@proofscript/compiler/dist/index.js')).href);
const { captureSourceGraph } = await import(pathToFileURL(path.join(packageRoot, 'bin/source-graph.mjs')).href);
const sourceRoot = path.join(packageRoot, 'node_modules/@proofscript/bootstrap/src/Ps/Bootstrap/SelfHost.' + variant);
const closure = await captureSourceGraph(runtime, sourceRoot, { packageDirectory: path.join(packageRoot, 'bin') });
const preservation = JSON.parse(await readFile(path.join(reportDir, 'source-preservation.json'), 'utf8'));
assert.equal(closure.sourceCount, preservation.closureModules, 'installed compiler closure differs from qualified source graph');
await closure.snapshot.revalidate();
await mkdir(path.join(projectDirectory, 'src'), { recursive: true });
await writeFile(path.join(projectDirectory, 'package.json'), JSON.stringify({ private: true, type: 'module', dependencies: { '@psc-fixture/math': '0.0.1' }, proofscript: { libraries: { Demo: '@psc-fixture/math' } } }) + '\n');
const lib = path.join(projectDirectory, 'node_modules/@psc-fixture/math');
await mkdir(path.join(lib, 'src/Demo'), { recursive: true });
await writeFile(path.join(lib, 'package.json'), JSON.stringify({ name: '@psc-fixture/math', version: '0.0.1', exports: { './package.json': './package.json' }, proofscript: { library: { schemaVersion: 1, modulePrefix: 'Demo', sourceRoot: 'src' } } }) + '\n');
await writeFile(path.join(lib, 'src/Demo/Math.' + variant), 'def demoAnswer : Nat := 42\n');
await writeFile(path.join(projectDirectory, 'src/Main.' + variant), 'import Demo.Math\n\ndef answer : Nat := demoAnswer\n');
const run = args => execFileSync(process.execPath, [cli, ...args], { cwd: projectDirectory, encoding: 'utf8', timeout: 180000, maxBuffer: 4 * 1024 * 1024 });
const audit = JSON.parse(run(['build', 'src/Main.' + variant, '--out', 'Main.js', '--json']));
assert.equal(audit.sourceCount, 2);
assert.equal(audit.claims.kernelAdmitted, true);
assert.equal(audit.claims.newSelfhostFixedPoint, false);
assert.equal(audit.receiptIsAuthority, false);
assert.equal(audit.kernel.provider, 'psc0-generated-js-core');
assert.match(audit.sourceClosureSha256, /^[0-9a-f]{64}$/u);
const program = await import(pathToFileURL(path.join(projectDirectory, 'Main.js')).href);
assert.equal(typeof program.answer === 'function' ? program.answer() : program.answer, 42n);
const primary = await readFile(path.join(projectDirectory, 'Main.js'), 'utf8');
assert.match(primary, /\.psc-artifacts/);
const canonical = await readFile(path.join(audit.artifactDirectory, 'Main.js'));
assert.equal(createHash('sha256').update(canonical).digest('hex'), audit.outputSha256);
await writeFile(path.join(projectDirectory, 'src/Invalid.' + variant), 'def answer : Nat := Type\n');
const negative = spawnSync(process.execPath, [cli, 'build', 'src/Invalid.' + variant, '--out', 'Main.js'], { cwd: projectDirectory, encoding: 'utf8', timeout: 90000 });
assert(!negative.error && negative.status !== 0, 'invalid input did not complete with refusal');
assert.equal(await readFile(path.join(projectDirectory, 'Main.js'), 'utf8'), primary, 'failed build replaced prior executable');
const unknown = spawnSync(process.execPath, [cli, 'build', 'src/Main.' + variant, '--unchecked'], { cwd: projectDirectory, encoding: 'utf8', timeout: 30000 });
assert(unknown.status !== 0 && unknown.stderr.includes('PSC_UNKNOWN_FLAG'), 'unknown flag not refused');
const report = { source: process.env.GITHUB_SHA, variant, node: process.version, platform: process.platform, packageScope: meta.proofscript.corePackages.length, installedCompilerClosureModules: closure.sourceCount, installedCompilerClosureParsed: true, checkedSourceModules: audit.sourceCount, importedSourceLibrary: true, kernelProvider: audit.kernel.provider, acceptedGraphBound: true, immutableGeneration: true, previousOutputSurvivesRefusal: true, unexpectedFlagsRefused: true, fullFixedPointExecuted: false };
await writeFile(path.join(reportDir, 'installed-' + variant + '.json'), JSON.stringify(report, null, 2) + '\n');
console.log('PSC_ARCHITECTURE_INSTALLED: PASS ' + JSON.stringify(report));
