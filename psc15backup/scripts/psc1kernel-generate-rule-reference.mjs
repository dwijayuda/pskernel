import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const packageRoot = path.join(root, "packages", "pskernel-core");
const compatibilityPath = path.join(packageRoot, "LEAN_4_34_COMPATIBILITY.json");
const conformancePath = path.join(packageRoot, "LEAN_4_34_CONFORMANCE.json");
const outputPath = path.join(packageRoot, "KERNEL_RULE_REFERENCE.md");
const check = process.argv.includes("--check");

const compatibility = JSON.parse(fs.readFileSync(compatibilityPath, "utf8"));
const conformance = JSON.parse(fs.readFileSync(conformancePath, "utf8"));
const coverage = new Map(conformance.rules.map((entry) => [entry.id, entry]));

const lines = [];
lines.push("# PSKernel Lean 4.34 Rule Reference", "");
lines.push(
  "Generated from `LEAN_4_34_COMPATIBILITY.json` and `LEAN_4_34_CONFORMANCE.json`.",
  "Do not edit this file by hand.",
  "",
  `Target: Lean ${compatibility.target.version} at \`${compatibility.target.gitCommit}\`.`,
  "",
  "For conceptual explanation and reading order, see `KERNEL_THEORY.md`.",
  "",
  "## Coverage summary",
  ""
);

let differential = 0;
let invariant = 0;
let pending = 0;
for (const entry of conformance.rules) {
  if (entry.coverage === "direct-differential") differential += 1;
  else if (entry.coverage === "direct-invariant") invariant += 1;
  else pending += 1;
}
lines.push(
  `- compatibility rules: **${compatibility.rules.length}**`,
  `- direct differential coverage: **${differential}**`,
  `- direct invariant coverage: **${invariant}**`,
  `- pending coverage: **${pending}**`,
  "",
  "## Rules",
  "",
  "| Rule | Meaning | PSKernel implementation | Lean 4.34 locator | Coverage | Concrete test |",
  "| --- | --- | --- | --- | --- | --- |"
);

for (const rule of compatibility.rules) {
  const test = coverage.get(rule.id);
  if (!test) {
    throw new Error(`PSC1KERNEL_RULE_REFERENCE_MISSING_CONFORMANCE: ${rule.id}`);
  }
  const symbol = `\`${rule.pskernelSymbol}\``;
  const testSymbol = test.testSymbol ? `\`${test.testSymbol}\`` : "—";
  lines.push(
    `| \`${rule.id}\` | ${rule.area} | ${symbol} | \`${rule.leanLocator}\` | ${test.coverage} | ${testSymbol} |`
  );
}

lines.push(
  "",
  "## Interpretation",
  "",
  "- **direct-differential**: the named test compares portable behavior with the frozen Lean-4.34-oriented PSC1Kernel reference.",
  "- **direct-invariant**: the named test checks a non-semantic runtime invariant directly; this is appropriate for cache/index representation rules.",
  "- A compatibility row being implemented is not enough for promotion; the conformance row must also remain non-pending.",
  "",
  "The authoritative development CI gates are:",
  "",
  "```text",
  "psc1kernel-compatibility-audit.mjs --require-complete",
  "psc1kernel-conformance-audit.mjs --require-complete",
  "psc1 check",
  "canonical .ps recheck",
  "differential executable",
  "```",
  "",
  "Generated fixed-point reproduction is a manual release/bootstrap checkpoint, not a normal development gate.",
  ""
);

const generated = lines.join("\n");
if (check) {
  if (!fs.existsSync(outputPath)) {
    throw new Error("PSC1KERNEL_RULE_REFERENCE_MISSING");
  }
  const current = fs.readFileSync(outputPath, "utf8");
  if (current !== generated) {
    throw new Error("PSC1KERNEL_RULE_REFERENCE_STALE");
  }
  console.log("PSC1KERNEL_RULE_REFERENCE: PASS");
} else {
  fs.writeFileSync(outputPath, generated);
  console.log(`PSC1KERNEL_RULE_REFERENCE: WROTE ${path.relative(root, outputPath)}`);
}
