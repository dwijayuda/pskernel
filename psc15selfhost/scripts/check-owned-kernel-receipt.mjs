import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { packageBySection } from './workspace-layout.mjs';
import { bootstrapPackageViolation } from './bootstrap-closure-contract.mjs';
import { defaultCheckedKernel } from './checked-kernel-provider.mjs';
import '../packages/pskernel-core/scripts/verify-evidence.mjs';

const manifest = JSON.parse(await readFile(new URL('../packages/pskernel-core/package.json', import.meta.url), 'utf8'));
assert.equal(manifest.version, '0.1.0-checker.6');
assert.equal(manifest.private, true);
assert.equal(manifest.proofscript.authoritative, false);
assert.equal(manifest.proofscript.bootstrap, true);
assert.equal(manifest.proofscript.portable, true);
assert(!existsSync(new URL('../packages/pskernel-core.old', import.meta.url)));
assert(!packageBySection.has('KernelCore'));
assert.equal(packageBySection.get('Kernel'), 'pskernel-core');
assert.equal(bootstrapPackageViolation('pskernel-core'), undefined);
for (const name of ['pskernel-core.old', 'pskernel-lean', 'pskernel-lean-wasm']) assert(bootstrapPackageViolation(name));
assert.equal(defaultCheckedKernel, 'pskernel-core');
const entry = await readFile(new URL('../packages/bootstrap/src/Ps/Bootstrap/SelfHost.lean', import.meta.url), 'utf8');
assert.match(entry, /^import Ps\.Kernel\.JointAdmission\s*$/mu);
const typing = await readFile(new URL('../packages/pskernel-core/src/Ps/Kernel/TypeCheck.lean', import.meta.url), 'utf8');
assert.match(typing, /^import Ps\.Kernel\.ExprInstantiate\s*$/mu);
assert(typing.includes('psKernelExprInstantiateStep current'));
assert(!typing.includes('psKernelExprInstantiateRun'));
const admission = await readFile(new URL('../packages/pskernel-core/src/Ps/Kernel/Admission.lean', import.meta.url), 'utf8');
assert(admission.includes('psKernelCheckWithParametersStart env (psKernelDefinitionParameters entry)'));
assert(admission.includes('PsKernelDefinitionBody.opaque => psKernelAdmissionReject PsKernelCheckError.unsupported'), 'external opaque declarations must remain rejected');
const reduction = await readFile(new URL('../packages/pskernel-core/src/Ps/Kernel/Reduction.lean', import.meta.url), 'utf8');
assert(reduction.includes('PsKernelDefinitionBody.opaque'));
const instantiate = await readFile(new URL('../packages/pskernel-core/src/Ps/Kernel/ExprInstantiate.lean', import.meta.url), 'utf8');
assert(instantiate.includes('PsKernelExprInstantiateTask.validate target'), 'even expressions without levels must validate parameter arity');
assert(instantiate.includes('psKernelLevelInstantiateStep current'), 'nested instantiation must consume the caller transition budget');
assert(!instantiate.includes('psKernelLevelInstantiateRun'), 'nested operations must not allocate an independent fuel budget');
const lake = await readFile(new URL('../lakefile.lean', import.meta.url), 'utf8');
assert(!lake.includes('lean_lib PsKernelCore where'));
const joint = await readFile(new URL('../packages/pskernel-core/src/Ps/Kernel/JointAdmission.lean', import.meta.url), 'utf8');
assert(joint.includes('PsKernelJointState.pending PsKernelList.nil entries'));
assert(joint.includes('psKernelAdmissionStep current'));
assert(joint.includes('psKernelUnitStep current'));
assert(!/psKernel(?:Admission|Unit)Run/u.test(joint));
const unit = await readFile(new URL('../packages/pskernel-core/src/Ps/Kernel/UnitInductive.lean', import.meta.url), 'utf8');
for (const transition of ['psKernelTypeStep current', 'psKernelConversionStep current', 'psKernelLookupStep current', 'psKernelOrderStep current']) assert(unit.includes(transition));
assert(!/psKernel(?:Type|Conversion|Lookup|Order)Run/u.test(unit));
const worker = await readFile(new URL('./checked-owned-kernel-worker.mjs', import.meta.url), 'utf8');
assert(worker.includes('k.psKernelJointStart(list(entries))'));
assert(worker.includes('k.psKernelJointStep(state)'));
assert(!worker.includes('psKernelUnitRecursorType'), 'host must not synthesize semantic recursor types');
console.log('PSC2_OWNED_KERNEL_RECEIPT: PASS (checker identities, retired legacy routing, owned bootstrap closure and default; release gates remain closed)');
